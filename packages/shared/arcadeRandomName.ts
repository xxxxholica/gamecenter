// 「おまかせ」で登録するときのランダムな名前(ネームエントリーの最大文字数以内のカタカナ)。

const NAMES = [
  'タロウ', 'ハナコ', 'ミケ', 'ポチ', 'ヒカリ', 'ソウタ', 'ミナト', 'ユウキ', 'アカリ', 'ハルカ',
  'ケンタ', 'サクラ', 'レン', 'ココア', 'モモ', 'ナギサ', 'リク', 'ソラ', 'ツバサ', 'メイ',
  'ダイチ', 'ミオ', 'カイト', 'ヨッシー', 'マル', 'コタロウ', 'ナナ', 'ショウ', 'ルカ', 'トモ',
];

export function randomArcadeName(): string {
  return NAMES[Math.floor(Math.random() * NAMES.length)];
}
